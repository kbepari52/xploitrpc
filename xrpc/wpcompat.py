PHP_EOL = {
    "8.3": None, "8.2": None, "8.1": None,
    "8.0": "2023-06-26",
    "7.4": "2022-11-28",
    "7.3": "2021-12-06",
    "7.2": "2020-11-30",
    "7.1": "2019-12-01",
    "7.0": "2018-12-03",
    "5.6": "2018-12-31",
}


def version_tuple(v: str) -> Tuple[int, ...]:
    try:
        return tuple(int(p) for p in re.findall(r"\d+", v)[:3])
    except Exception:
        return (0,)


def assess_wp_version(version: str) -> Tuple[str, str]:
    """Return (severity, note) for a WordPress version string."""
    vt = version_tuple(version)
    for ref, severity, note in WP_VERSION_NOTES:
        if vt < version_tuple(ref):
            continue
        return severity, "%s: %s" % (version, note)
    return "info", "%s: recent version" % version


def assess_php_version(powered_by: str) -> Tuple[str, str]:
    """Return (severity, note) for an X-Powered-By PHP version."""
    m = re.search(r"PHP[ /]([0-9]+\.[0-9]+)", powered_by or "")
    if not m:
        return "info", ""
    ver = m.group(1)
    eol = PHP_EOL.get(ver)
    if eol is None:
        return "info", "PHP %s: supported" % ver
    try:
        from datetime import date
        y, mo, d = (int(p) for p in eol.split("-"))
        if date.today() >= date(y, mo, d):
            return "high", "PHP %s: END OF LIFE since %s. No security fixes." % (ver, eol)
        return "low", "PHP %s: security support ends %s" % (ver, eol)
    except Exception:
        return "info", ""


