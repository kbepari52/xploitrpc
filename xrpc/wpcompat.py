"""
wpcompat.py - WordPress / XML-RPC compatibility layer for xploitrpc.

Real WordPress installs are not uniform. Between the operator and xmlrpc.php
there is usually a CDN, a WAF, a caching layer, or all three, and any of them
can rewrite, block, throttle or lie about the response. This module exists so
the main tool can answer three questions before it draws a conclusion:

    1. What is actually in front of this site?          -> detect_stack()
    2. Where is the XML-RPC endpoint, if it moved?      -> discover_endpoints()
    3. Which advertised methods actually work?          -> probe_method_matrix()

Standard library only. No third-party dependencies.

Author : Krishanu Bepari (github.com/kbepari52)
License: MIT
"""

