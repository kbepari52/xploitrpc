def is_throttled(status: int, headers: Dict[str, str], body: str = "") -> bool:
    """True when a response looks like rate limiting rather than a real answer."""
    if status == 429:
        return True
    if status == 503 and (headers or {}).get("retry-after"):
        return True
    low = (body or "")[:2000].lower()
    return any(token in low for token in (
        "rate limit", "too many requests", "slow down", "temporarily blocked",
    ))
