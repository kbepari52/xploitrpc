def map_namespaces(methods: Sequence[str]) -> Dict[str, str]:
    """Return {namespace: plugin guess} for namespaces beyond WP core."""
    core_prefixes = ("system.", "wp.", "blogger.", "metaWeblog.", "mt.",
                     "pingback.", "demo.")
    found: Dict[str, str] = {}
    for m in methods:
        ns = m.split(".")[0] if "." in m else ""
        if not ns or any(m.startswith(p) for p in core_prefixes):
            continue
        if ns not in found:
            found[ns] = PLUGIN_NAMESPACES.get(ns, "unknown plugin (namespace %s)" % ns)
    return found
