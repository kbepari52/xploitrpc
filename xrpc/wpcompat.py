@dataclass
class StackInfo:
    """What sits between the operator and WordPress."""
    server: str = ""
    powered_by: str = ""
    detected: List[str] = field(default_factory=list)
    notes: List[str] = field(default_factory=list)
    headers: Dict[str, str] = field(default_factory=dict)
    status: int = 0
    cdn_cache: str = ""

    def has_waf(self) -> bool:
        blocking = {"cloudflare", "sucuri", "wordfence", "imperva", "akamai", "mod_security"}
        return any(d in blocking for d in self.detected)

    def summary(self) -> str:
        if not self.detected:
            return "no known edge/WAF signature"
        return ", ".join(self.detected)


def detect_stack(headers: Dict[str, str], body: str = "", status: int = 0) -> StackInfo:
    """Identify CDN/WAF/server from a response's headers and body."""
    info = StackInfo(status=status)
    lowered = {k.lower(): (v or "") for k, v in headers.items()}
    info.headers = lowered
    info.server = lowered.get("server", "")
    info.powered_by = lowered.get("x-powered-by", "")
    info.cdn_cache = (
        lowered.get("x-cache", "")
        or lowered.get("x-cache-hit", "")
        or lowered.get("x-litespeed-cache", "")
        or lowered.get("x-hostinger-cache", "")
    )

    cookie_blob = lowered.get("set-cookie", "")
    body_sample = (body or "")[:60000]

    for name, sig in WAF_SIGNATURES.items():
        hit = False
        for header, pattern in sig.get("headers", {}).items():
            if re.search(pattern, lowered.get(header, ""), re.I):
                hit = True
                break
        if not hit:
            for cookie in sig.get("cookies", ()):
                if cookie.lower() in cookie_blob.lower():
                    hit = True
                    break
        if not hit:
            for pattern in sig.get("body", ()):
                if re.search(pattern, body_sample, re.I):
                    hit = True
                    break
        if hit:
            info.detected.append(name)
            if sig.get("note"):
                info.notes.append(sig["note"])

    return info


# ===========================================================================
# Response classification
# ===========================================================================

class ResponseKind:
    XMLRPC = "xmlrpc"
    HTML = "html"
    JSON = "json"
    EMPTY = "empty"
    BINARY = "binary"
    CHALLENGE = "challenge"   # bot interstitial, not a real answer
    THROTTLED = "throttled"   # rate limited


# Interstitial pages served by CDNs and anti-bot layers before the real request
# is allowed through. These are not "the endpoint is missing" and they are not
# "XML-RPC is disabled" - they mean the request never reached WordPress.
CHALLENGE_MARKERS = (
    "one moment, please",
    "checking your browser",
    "just a moment",
    "ddos-guard",
    "ddos guard",
    "please wait while we verify",
    "verifying you are human",
    "enable javascript and cookies to continue",
    "cf-browser-verification",
    "attention required",
    "pardon our interruption",
    "request unsuccessful. incapsula",
    "you are being redirected",
    "security check",
)

THROTTLE_MARKERS = (
    "too many requests",
    "rate limit",
    "slow down",
    "temporarily blocked",
    "request blocked",
    "exceeded the limit",
)


def classify_body(raw: bytes) -> Tuple[str, str]:
    """
    Decide what a response body actually is.

    Returns (kind, explanation). This matters because a WAF block page, a
    Cloudflare challenge and a genuine "XML-RPC is disabled" notice all arrive
    as HTTP 200 or 403 with HTML, and a naive parser reports them all as
    "not XML-RPC" without telling the operator which one it was.
    """
    if not raw or not raw.strip():
        return ResponseKind.EMPTY, "empty body"

    head = raw[:8000]
    stripped = head.lstrip()

    if stripped.startswith(b"<?xml") or stripped.startswith(b"<methodResponse") \
            or stripped.startswith(b"<methodCall"):
        return ResponseKind.XMLRPC, "XML-RPC document"

    if stripped.startswith(b"{") or stripped.startswith(b"["):
        return ResponseKind.JSON, "JSON document"

    low = stripped.lower()
    if low.startswith(b"<!doctype html") or low.startswith(b"<html") or b"<html" in low[:500]:
        text = head.decode("utf-8", errors="replace")
        text_low = text.lower()

        # Check throttling and bot interstitials before the named WAF products,
        # because a challenge page is the most actionable thing we can report:
        # it means "back off", not "this site has no XML-RPC".
        for marker in THROTTLE_MARKERS:
            if marker in text_low:
                return ResponseKind.THROTTLED, "rate-limit / throttle page (%r)" % marker

        for marker in CHALLENGE_MARKERS:
            if marker in text_low:
                return ResponseKind.CHALLENGE, "bot challenge interstitial (%r)" % marker

        if "cloudflare" in text_low and ("attention required" in text_low or "cf-error" in text_low):
            return ResponseKind.CHALLENGE, "Cloudflare challenge/block page"
        if "sucuri" in text_low:
            return ResponseKind.CHALLENGE, "Sucuri firewall block page"
        if "incapsula" in text_low or "imperva" in text_low:
            return ResponseKind.CHALLENGE, "Imperva/Incapsula block page"
        if "wordfence" in text_low:
            return ResponseKind.CHALLENGE, "Wordfence block page"
        if "xml-rpc services are disabled" in text_low or "xmlrpc services are disabled" in text_low:
            return ResponseKind.HTML, "WordPress 'XML-RPC disabled' notice"
        if "mod_security" in text_low or "not acceptable" in text_low:
            return ResponseKind.CHALLENGE, "ModSecurity rejection page"
        if "404" in text_low[:200] or "not found" in text_low[:400]:
            return ResponseKind.HTML, "HTML 404 / not found page"
        return ResponseKind.HTML, "HTML page (not XML-RPC)"

    return ResponseKind.BINARY, "unrecognised binary payload"


# ===========================================================================
# Endpoint discovery
# ===========================================================================
#
# xmlrpc.php is the default but not the only location. Sites move it, hide it
# behind a rewrite, or expose it under a subdirectory install.

DEFAULT_CANDIDATE_PATHS: Tuple[str, ...] = (
    "/xmlrpc.php",
    "/wp/xmlrpc.php",
    "/wordpress/xmlrpc.php",
    "/blog/xmlrpc.php",
    "/wp-includes/xmlrpc.php",
    "/xmlrpc",
    "/xml-rpc.php",
    "/XMLRPC.php",
    "/wp-json/wp/v2/",
)


@dataclass
class EndpointCandidate:
    url: str
    status: int
    kind: str
    detail: str
    live: bool = False


def _base_of(url: str) -> str:
    parts = urllib.parse.urlsplit(url)
    path = parts.path or "/"
    if path.endswith("xmlrpc.php") or path.endswith(".php"):
        path = path.rsplit("/", 1)[0] + "/"
    elif not path.endswith("/"):
        path = path + "/"
    return urllib.parse.urlunsplit((parts.scheme, parts.netloc, path, "", ""))


def discover_endpoints(
    opener: urllib.request.OpenerDirector,
    base_url: str,
    timeout: float = 15.0,
    user_agent: str = "xploitrpc",
    paths: Sequence[str] = DEFAULT_CANDIDATE_PATHS,
    verbose: bool = False,
) -> List[EndpointCandidate]:
    """
    Probe common XML-RPC locations and report which ones answer.

    A candidate is "live" when it returns a well-formed XML-RPC document for
    system.listMethods. Anything else is recorded with its real classification
    so a block page is not mistaken for a dead endpoint.
    """
    base = _base_of(base_url)
    body = (
        b"<?xml version='1.0'?><methodCall>"
        b"<methodName>system.listMethods</methodName><params></params></methodCall>"
    )
    results: List[EndpointCandidate] = []

    for path in paths:
        url = urllib.parse.urljoin(base, path.lstrip("/"))
        req = urllib.request.Request(
            url,
            data=body,
            method="POST",
            headers={
                "Content-Type": "text/xml; charset=utf-8",
                "Accept": "text/xml",
                "User-Agent": user_agent,
                "Connection": "close",
            },
        )
        status = 0
        raw = b""
        try:
            with opener.open(req, timeout=timeout) as resp:
                status = getattr(resp, "status", resp.getcode())
                raw = resp.read(200000)
        except urllib.error.HTTPError as exc:
            status = exc.code
            try:
                raw = exc.read(200000)
            except Exception:
                raw = b""
        except Exception as exc:
            results.append(EndpointCandidate(url, 0, "error", str(exc)[:80]))
            if verbose:
                print("    %-34s error: %s" % (path, str(exc)[:60]))
            continue

        if raw[:2] == b"\x1f\x8b":
            try:
                raw = gzip.decompress(raw)
            except Exception:
                pass

        kind, detail = classify_body(raw)
        live = False
        if kind == ResponseKind.XMLRPC:
            try:
                values, _ = xmlrpc.client.loads(raw)
                val = values[0] if values else None
                if isinstance(val, list):
                    live = True
                    detail = "%d methods" % len(val)
            except Exception:
                detail = "XML-RPC header but unparseable"

        results.append(EndpointCandidate(url, status, kind, detail, live))
        if verbose:
            print("    %-34s %s %-8s %s" % (path, status, kind, detail))

    return results


# ===========================================================================
# Method availability matrix
# ===========================================================================

class MethodStatus:
    WORKS = "works"
    FILTERED = "filtered"      # advertised but removed by a security plugin
    NEEDS_AUTH = "needs_auth"  # exists, rejects unauthenticated call
    BAD_ARGS = "bad_args"      # exists, rejects our argument shape
    ERROR = "error"
    UNKNOWN = "unknown"


@dataclass
class MethodResult:
    method: str
    status: str
    fault_code: Optional[int] = None
    detail: str = ""


# Methods that are safe to call with no arguments and no credentials. These
# reveal whether a method exists without performing any action.
_SAFE_PROBES: Dict[str, Tuple[Any, ...]] = {
    "system.listMethods": (),
    "system.getCapabilities": (),
    "system.methodHelp": ("system.listMethods",),
    "system.methodSignature": ("system.listMethods",),
    "demo.sayHello": (),
    "demo.addTwoNumbers": (1, 2),
    "mt.supportedMethods": (),
    "mt.supportedTextFilters": (),
    "pingback.extensions.getPingbacks": ("http://example.com/",),
}

# For everything else we call with no arguments on purpose. A method that has
# been removed by a security plugin answers -32601 "method not found"; a method
# that still exists answers 400 "insufficient arguments". That difference
# reveals filtering without attempting authentication or changing anything.
_PROBE_WITH_NO_ARGS = True


def probe_method_matrix(
    client: Any,
    methods: Sequence[str],
    verbose: bool = False,
    delay: float = 0.0,
) -> List[MethodResult]:
    """
    Determine, per method, whether it genuinely exists on this install.

    Many hardened WordPress sites advertise the full method list from
    system.listMethods but then strip wp.* methods at the xmlrpc_methods
    filter. Calling with no arguments distinguishes the two cases without
    authenticating or mutating anything.
    """
    results: List[MethodResult] = []

    for method in methods:
        if delay:
            time.sleep(delay)
        args = _SAFE_PROBES.get(method, () if _PROBE_WITH_NO_ARGS else None)
        if args is None:
            continue

        try:
            client.call(method, *args)
            results.append(MethodResult(method, MethodStatus.WORKS, None, "returned a value"))
            continue
        except Exception as exc:
            code = getattr(exc, "code", None)
            message = (getattr(exc, "message", "") or str(exc) or "").lower()

        if code == -32601 or "does not exist" in message or "method not found" in message:
            status, detail = MethodStatus.FILTERED, "method not found (removed or disabled)"
        elif code == -32602 or "insufficient arguments" in message or "invalid params" in message:
            status, detail = MethodStatus.BAD_ARGS, "exists, wants arguments"
        elif code in (403, 401) or "incorrect username" in message:
            status, detail = MethodStatus.NEEDS_AUTH, "exists, requires valid credentials"
        elif code == 405 or "disabled" in message:
            status, detail = MethodStatus.FILTERED, "disabled on this install"
        elif code == 404 or "not found" in message:
            status, detail = MethodStatus.BAD_ARGS, "exists, object not found"
        elif code == 0:
            # WordPress returns a bare fault 0 for pingback rejections and other
            # "exists but refused this input" cases. The method is present.
            status, detail = MethodStatus.BAD_ARGS, "exists, rejected this input (fault 0)"
        else:
            status, detail = MethodStatus.ERROR, "fault %s: %s" % (code, message[:60])

        results.append(MethodResult(method, status, code, detail))
        if verbose:
            print("    %-42s %-11s %s" % (method, status, detail))

    return results


